// 12 original levels on a 36x20 tile grid (T = 32 px). Row 0 is the ceiling,
// rows 18-19 the floor, columns 0 and 35 the walls. A hero stands IN a row,
// on top of the row below it.
//
// Grid legend:
//   #  rock                     =  one-way platform (land on it from above)
//   F  fire pool  (Дөл wades through, kills Дусал)
//   W  water pool (Дусал wades through, kills Дөл)
//   G  poison     (kills both)
//   r  red gem (Дөл)            b  blue gem (Дусал)        max 32 per level
//   A  Дөл spawn                B  Дусал spawn
//   D  Дөл's exit door          E  Дусал's exit door (door = this tile + the
//                                  one above; stand grounded in front of it)
//
// Level fields:
//   name   { mn, en }  shown in the level list / HUD
//   par    3-star time in seconds = ceil(solo solver seconds × 1.5) + 5
//          (`node tools/solve.mjs` prints the value it expects in column par*)
//   grid   20 strings × 36 chars
//   plates {x,y,ch}         pressed while a hero stands on tile (x,y)
//   levers {x,y,ch}         toggled each time a hero touches the tile (a lever
//                           one row above a floor is pulled by jumping)
//   gates  {x,y,h,ch}       solid column of h tiles from row y; opens while
//                           its channel is active
//   lifts  {x,y,w,dx,dy,ch} w tiles wide, top surface at row y; glides to
//                           (x+dx, y+dy) while active, back when inactive
// Channels 1-8: active = any plate on it pressed OR its lever toggled on.
//
// Every level is proven beatable in SOLO mode (one player switching heroes,
// the idle hero standing still) with every gem reachable, by
// `node tools/solve.mjs` — run it after any change here.

